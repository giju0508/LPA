@lru_cache(maxsize=1)
def _conductivity_interpolator():
    import numpy as np
    from scipy.interpolate import LinearNDInterpolator
    points = np.asarray([(t, p) for _, t, p, _ in CONDUCTIVITY_DATA], dtype=float)
    values = np.asarray([k for _, _, _, k in CONDUCTIVITY_DATA], dtype=float)
    # Rescaling gives kelvin and MPa comparable numerical weight. The convex
    # hull enforces the actual measured domain, not its enclosing rectangle.
    return LinearNDInterpolator(points, values, fill_value=nan, rescale=True)


def rp1_conductivity(temperature_k: float, pressure_pa: float) -> float:
    """Measured-data interpolation; nan outside the sampled convex hull."""
    value = float(_conductivity_interpolator()(temperature_k, pressure_pa/1e6))
    return value if isfinite(value) and value > 0 else nan


def rp1_kinematic_viscosity(temperature_k: float) -> float:
    """NISTIR 6646 Eq. (1), m2/s, only inside the 243.29-333.15 K fit range."""
    if not VISCOSITY_TEMPERATURE_RANGE_K[0] <= temperature_k <= VISCOSITY_TEMPERATURE_RANGE_K[1]:
        return nan
    t = temperature_k
    return 1e-6*exp(-7.812 + 5530.0/t - 1.503e6/t**2 + 1.801e8/t**3)


def _screening_density(temperature_k: float) -> float:
    return 810.0*(1.0-7e-4*(temperature_k-293.15))


@lru_cache(maxsize=1)
def _viscosity_product_interpolator():
    import numpy as np
    from scipy.interpolate import LinearNDInterpolator
    points = [(t, p) for p, t, _ in VISCOSITY_PRODUCT_DATA]
    products = [product for _, _, product in VISCOSITY_PRODUCT_DATA]
    return LinearNDInterpolator(
        np.asarray(points), np.log(np.asarray(products)), fill_value=nan,
        rescale=True,
    )


def rp1_viscosity_density_product(temperature_k: float, pressure_pa: float) -> float:
    """Bounded log interpolation of the original 30 Table 12 measurements.

    No extrapolation is performed. Atmospheric Eq. (1) points are not merged:
    the instruments' results differ, and merging them invents sharp pressure
    trends. The measured convex hull does not certify phase stability.
    """
    value = float(_viscosity_product_interpolator()(temperature_k, pressure_pa/1e6))
    return exp(value) if isfinite(value) else nan


def rp1_estimate(temperature_k: float, pressure_pa: float) -> dict:
    """Explicit partial-data estimate; Cp/rho are still screening, phase unknown."""
    delta = temperature_k-293.15
    density = _screening_density(temperature_k)
    cp = 2050.0*(1.0+2e-4*delta)
    enthalpy = 2050.0*(delta+1e-4*delta**2)
    k_measured = rp1_conductivity(temperature_k, pressure_pa)
    viscosity_nu = rp1_kinematic_viscosity(temperature_k)
    viscosity_product = rp1_viscosity_density_product(temperature_k, pressure_pa)
    # Keep a single temperature-bounded diagnostic curve. Switching to the
    # inconsistent Table 12 instrument data as its hull is entered would invent
    # a discontinuity. The independent Table 12 product is exposed as evidence,
    # never spliced into this atmospheric default or called a pressure model.
    mu = viscosity_nu*density if isfinite(viscosity_nu) and density > 0 else nan
    conductivity = k_measured if isfinite(k_measured) else .135*(1.0-2e-4*delta)
    issues = [
        "RP-1: no validated pressure/phase equation of state; phase unknown",
        "RP-1 density and Cp remain pressure-independent screening estimates; no measured validity range claimed",
        "RP-1 NIST viscosity data describe an atypical high-olefin sample; actual lot may differ",
    ]
    if isfinite(viscosity_nu):
        viscosity_source = "NISTIR 6646 atmospheric Eq. (1) times screening density"
        issues.append("RP-1 dynamic viscosity is a pressure-independent screening diagnostic from atmospheric NIST kinematic viscosity times screening density; no validated compressed-liquid pressure correction")
    else:
        viscosity_source = "no viscosity data at this pressure/temperature"
        issues.append("RP-1 default viscosity outside NIST Eq. (1) fit range [243.29, 333.15] K; extrapolation and viscosity floor disabled")
    if isfinite(viscosity_product):
        issues.append("NIST Table 12 mu*rho is separate evidence only; instrument-resolution uncertainty prevents splicing it into the atmospheric viscosity curve")
    if not isfinite(k_measured):
        issues.append("RP-1 conductivity outside NIST Table 10 measured convex hull; reference screening estimate used")
    evidence = (
        dict(property_name="kinematic_viscosity_m2_s", source="NISTIR 6646 Eq. (1), original sample",
             applicability="bounded_empirical" if isfinite(viscosity_nu) and pressure_pa == VISCOSITY_REFERENCE_PRESSURE_PA else "screening" if isfinite(viscosity_nu) else "unsupported",
             temperature_range_k=VISCOSITY_TEMPERATURE_RANGE_K,
             pressure_range_pa=(VISCOSITY_REFERENCE_PRESSURE_PA,VISCOSITY_REFERENCE_PRESSURE_PA),
             notes=("fit to atmospheric measurements; not a compressed-liquid pressure correlation",)),
        dict(property_name="viscosity_pa_s", source=viscosity_source,
             applicability="screening" if isfinite(mu) else "unsupported",
             temperature_range_k=VISCOSITY_TEMPERATURE_RANGE_K, pressure_range_pa=None,
             notes=("atmospheric Eq. (1), multiplied by screening density; pressure independence is a diagnostic assumption only",
                    "density conversion, operating pressure, and actual fuel-lot applicability are not validated")),
        dict(property_name="viscosity_density_product_kg2_m4_s", source="NISTIR 6646 Table 12, separate instrument data",
             applicability="measured_interpolation" if isfinite(viscosity_product) else "unsupported",
             value=viscosity_product if isfinite(viscosity_product) else None,
             temperature_range_k=None, pressure_range_pa=None,
             notes=("not used by the default dynamic-viscosity curve; no automatic join between inconsistent instruments",
                    "log-linear interpolation only inside the original measured (T,P) convex hull",
                    "instrument-resolution limitations; model deviations -3.5 to -11.7 percent in report, p. 65")),
        dict(property_name="conductivity_w_mk", source="NISTIR 6646 Table 10 lambda_c" if isfinite(k_measured) else "reference screening estimate",
             applicability="measured_interpolation" if isfinite(k_measured) else "screening",
             temperature_range_k=None, pressure_range_pa=None,
             notes=("valid only inside measured (Te,P) convex hull; bounding rectangle is insufficient",
                    "650 K measurements include reaction/composition/time dependence and approximately 4 percent uncertainty; not clean-fuel validation",
                    "sparse-data interpolation has no separately validated uncertainty and the source lot was atypical",)),
        dict(property_name="density_kg_m3", source="legacy reference-temperature screening estimate",
             applicability="screening", temperature_range_k=None, pressure_range_pa=None, notes=("no pressure correction",)),
        dict(property_name="specific_heat_j_kgk", source="legacy reference-temperature screening estimate",
             applicability="screening", temperature_range_k=None, pressure_range_pa=None, notes=("enthalpy integrates this Cp exactly; no independent EOS validation",)),
    )
    unsupported = not all(isfinite(v) and v>0 for v in (density,cp,conductivity,mu))
    return dict(density_kg_m3=density, specific_heat_j_kgk=cp,
                conductivity_w_mk=conductivity, viscosity_pa_s=mu,
                enthalpy_j_kg=enthalpy, issues=tuple(issues),
                property_applicability="unsupported" if unsupported else "screening",
                property_evidence=evidence,
                transport_source="NISTIR 6646 partial measurements plus explicit screening estimates")
